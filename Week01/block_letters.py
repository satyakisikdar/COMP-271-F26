def _self_check():
    """Every letter must be a 10-row, 10-column grid. Run directly (uv run
    block_letters.py) to sanity-check the placeholder set after editing it."""
    letters = {
        name: value
        for name, value in globals().items()
        if len(name) == 1 and name.isalpha() and isinstance(value, list)
    }
    assert len(letters) == 26, f"expected 26 letters, found {len(letters)}"
    for name, rows in letters.items():
        assert len(rows) == 10, f"letter {name!r} has {len(rows)} rows, expected 10"
        for row in rows:
            assert len(row) == 10, f"letter {name!r} has a row of length {len(row)}, expected 10: {row!r}"
    print(f"OK: all {len(letters)} letters are 10x10.")


if __name__ == "__main__":
    _self_check()
